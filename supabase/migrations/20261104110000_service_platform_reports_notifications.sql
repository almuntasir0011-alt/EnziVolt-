create table if not exists public.service_work_reports (
  id bigint generated by default as identity primary key,
  request_id text not null references public.service_requests(request_id) on delete cascade,
  assignment_id bigint not null references public.technician_assignments(id) on delete cascade,
  technician_user_id uuid not null references auth.users(id) on delete restrict,
  work_summary text not null check (length(btrim(work_summary)) between 5 and 3000),
  work_performed text not null check (length(btrim(work_performed)) between 5 and 6000),
  materials_used text not null default '' check (length(materials_used) <= 3000),
  customer_note text not null default '' check (length(customer_note) <= 2000),
  completion_state text not null default 'submitted'
    check (completion_state in ('submitted','reviewed','needs_followup')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (assignment_id)
);

create table if not exists public.service_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  request_id text references public.service_requests(request_id) on delete cascade,
  event_type text not null check (event_type in (
    'request_received','request_status','technician_assigned',
    'assignment_accepted','assignment_declined','work_started',
    'work_completed','new_message','work_report'
  )),
  title text not null check (length(btrim(title)) between 2 and 160),
  body text not null default '' check (length(body) <= 1000),
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists service_work_reports_request_idx
  on public.service_work_reports(request_id, created_at desc);
create index if not exists service_notifications_user_idx
  on public.service_notifications(user_id, created_at desc);

alter table public.service_work_reports enable row level security;
alter table public.service_notifications enable row level security;

grant select, insert, update on public.service_work_reports to authenticated;
grant select, update on public.service_notifications to authenticated;
grant usage, select on sequence public.service_work_reports_id_seq to authenticated;

drop policy if exists service_work_reports_select_participant on public.service_work_reports;
create policy service_work_reports_select_participant
on public.service_work_reports for select to authenticated
using (
  (select private.is_active_admin())
  or technician_user_id = (select auth.uid())
  or exists (
    select 1 from public.service_requests sr
    where sr.request_id = service_work_reports.request_id
      and sr.customer_user_id = (select auth.uid())
  )
);

drop policy if exists service_work_reports_insert_assigned_technician on public.service_work_reports;
create policy service_work_reports_insert_assigned_technician
on public.service_work_reports for insert to authenticated
with check (
  technician_user_id = (select auth.uid())
  and exists (
    select 1 from public.technician_assignments ta
    join public.technician_profiles tp on tp.user_id = ta.technician_user_id
    where ta.id = service_work_reports.assignment_id
      and ta.request_id = service_work_reports.request_id
      and ta.technician_user_id = (select auth.uid())
      and tp.active = true
      and ta.status in ('accepted','in_progress','completed')
  )
);

drop policy if exists service_work_reports_update_admin on public.service_work_reports;
create policy service_work_reports_update_admin
on public.service_work_reports for update to authenticated
using ((select private.is_active_admin()))
with check ((select private.is_active_admin()));

drop policy if exists service_notifications_select_own_or_admin on public.service_notifications;
create policy service_notifications_select_own_or_admin
on public.service_notifications for select to authenticated
using (user_id = (select auth.uid()) or (select private.is_active_admin()));

drop policy if exists service_notifications_update_own on public.service_notifications;
create policy service_notifications_update_own
on public.service_notifications for update to authenticated
using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));

-- Notifications are generated only by trusted database triggers, never by browser clients.
revoke insert, delete on public.service_notifications from anon, authenticated;

create or replace function private.notify_service_participants(
  p_user_id uuid,
  p_request_id text,
  p_event_type text,
  p_title text,
  p_body text
) returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_user_id is not null then
    insert into public.service_notifications(user_id, request_id, event_type, title, body)
    values (p_user_id, p_request_id, p_event_type, p_title, left(coalesce(p_body,''),1000));
  end if;
end;
$$;
revoke all on function private.notify_service_participants(uuid,text,text,text,text) from public, anon, authenticated;

create or replace function private.on_service_assignment_notification()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare v_customer uuid;
begin
  select customer_user_id into v_customer
  from public.service_requests where request_id = new.request_id;

  if tg_op = 'INSERT' then
    perform private.notify_service_participants(
      new.technician_user_id,new.request_id,'technician_assigned',
      'New job assigned','A service request has been assigned to you.'
    );
  elsif new.status is distinct from old.status then
    if new.status = 'accepted' then
      perform private.notify_service_participants(v_customer,new.request_id,'assignment_accepted',
        'Technician accepted the job','The assigned technician accepted your request.');
    elsif new.status = 'declined' then
      perform private.notify_service_participants(v_customer,new.request_id,'assignment_declined',
        'Technician declined the job','The assignment needs administrator review.');
    elsif new.status = 'in_progress' then
      perform private.notify_service_participants(v_customer,new.request_id,'work_started',
        'Work started','The technician has started the assigned work.');
    elsif new.status = 'completed' then
      perform private.notify_service_participants(v_customer,new.request_id,'work_completed',
        'Work completed','The technician marked the assigned work as completed.');
    end if;
  end if;
  return new;
end;
$$;
revoke all on function private.on_service_assignment_notification() from public, anon, authenticated;

drop trigger if exists trg_service_assignment_notifications on public.technician_assignments;
create trigger trg_service_assignment_notifications
after insert or update of status on public.technician_assignments
for each row execute function private.on_service_assignment_notification();

create or replace function private.on_service_message_notification()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare v_customer uuid; v_recipient uuid;
begin
  select customer_user_id into v_customer
  from public.service_requests where request_id = new.request_id;

  if v_customer is not null and v_customer <> new.sender_user_id then
    v_recipient := v_customer;
  else
    select ta.technician_user_id into v_recipient
    from public.technician_assignments ta
    where ta.request_id = new.request_id
      and ta.technician_user_id <> new.sender_user_id
    order by ta.assigned_at desc limit 1;
  end if;

  if v_recipient is not null then
    perform private.notify_service_participants(v_recipient,new.request_id,'new_message',
      'New service message','You have a new message about your service request.');
  end if;
  return new;
end;
$$;
revoke all on function private.on_service_message_notification() from public, anon, authenticated;

drop trigger if exists trg_service_message_notifications on public.service_messages;
create trigger trg_service_message_notifications
after insert on public.service_messages
for each row execute function private.on_service_message_notification();

create or replace function private.on_service_request_status_notification()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.status is distinct from old.status and new.customer_user_id is not null then
    perform private.notify_service_participants(new.customer_user_id,new.request_id,'request_status',
      'Service request updated','Your service request status is now: ' || new.status || '.');
  end if;
  return new;
end;
$$;
revoke all on function private.on_service_request_status_notification() from public, anon, authenticated;

drop trigger if exists trg_service_request_status_notifications on public.service_requests;
create trigger trg_service_request_status_notifications
after update of status on public.service_requests
for each row execute function private.on_service_request_status_notification();

